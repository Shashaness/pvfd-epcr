import 'dart:io';
import 'dart:typed_data';
import 'package:flutter_test/flutter_test.dart';
import 'package:pvfd_epcr/services/maps_service.dart';
import 'package:pvfd_epcr/services/printing_service.dart';
import 'package:pvfd_epcr/services/sharing_service.dart';

void main() {
  test(
    'sharing retains PDF and XML subjects, text and original export paths',
    () async {
      final calls = <List<String>>[];
      final service = SharingService(
        share: (file, subject, text) async {
          calls.add([file.path, subject, text]);
        },
      );
      await service.sharePdf(File('/synthetic/document.pdf'), 'synthetic-id');
      await service.shareXml(File('/synthetic/document.xml'), 'synthetic-id');
      expect(calls, [
        [
          '/synthetic/document.pdf',
          'PVFD ePCR synthetic-id',
          'Attached is the PDF for PVFD ePCR synthetic-id.',
        ],
        [
          '/synthetic/document.xml',
          'PVFD ePCR synthetic-id',
          'Attached NEMSIS XML for PVFD ePCR synthetic-id.',
        ],
      ]);
    },
  );
  test('printing forwards generated bytes and safe legacy filename', () async {
    final bytes = Uint8List.fromList([37, 80, 68, 70]);
    final service = PrintingService(
      print: (actual, name) async {
        expect(actual, bytes);
        expect(name, 'PVFD_ePCR_legacy%2Fid.pdf');
      },
    );
    await service.printPdf(bytes, 'legacy/id');
  });
  test(
    'maps preserves HTTPS external search semantics and escaped address',
    () async {
      Uri? launched;
      final service = MapsService(
        launch: (uri) async {
          launched = uri;
          return true;
        },
      );
      expect(await service.openAddress('  100 Synthetic & Test Lane  '), true);
      expect(launched!.scheme, 'https');
      expect(launched!.host, 'www.google.com');
      expect(launched!.queryParameters['query'], '100 Synthetic & Test Lane');
      expect(launched!.queryParameters['api'], '1');
    },
  );
}
